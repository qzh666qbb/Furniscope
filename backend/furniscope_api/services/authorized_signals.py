    async def _upsert_dataset_listing(self, session: AsyncSession, *, tenant_id: int,
                                      source: dict[str, Any], item: dict[str, Any]) -> int | None:
        """Keep the bound AI dataset's current listing row in sync with a live source.

        Full point-in-time history remains in competitor_listing_snapshots.  The market
        dataset deliberately stores one current row per platform listing so list counts,
        previews, and workflow inputs do not grow on every scheduled fetch.
        """
        dataset_id = source.get("dataset_id")
        asin = str(item.get("platform_listing_id") or item.get("asin") or "").strip().upper()
        if not dataset_id or not asin:
            return None
        captured_at = _parse_datetime(item.get("captured_at")) or _now()
        rating = _float(item.get("rating"))
        rating = rating if rating is None or 0 <= rating <= 5 else None
        sale_price = max(0.0, _float(item.get("sale_price")) or 0.0)
        list_price = _float(item.get("list_price"))
        list_price = max(0.0, list_price) if list_price is not None else None
        attributes = {
            **(item.get("normalized_attributes") or {}),
            "market_country": source.get("market_country") or "US",
            "collection_source_kind": source.get("source_kind"),
            "authorization_reference": source.get("authorization_reference"),
        }
        params = {
            "tenant": tenant_id, "dataset": int(dataset_id), "platform_id": asin,
            "url": item.get("source_url") or source.get("endpoint_url"),
            "title": str(item.get("title") or f"{source.get('platform', 'market')} {asin}"),
            "category": str(item.get("category_code") or source.get("category_code") or "uncategorized"),
            "currency": str(item.get("currency") or "USD")[:3].upper(),
            "list_price": list_price, "sale_price": sale_price, "brand": item.get("brand"),
            "rating": rating, "review_count": max(0, _int(item.get("review_count")) or 0),
            "captured": captured_at, "first_available": item.get("first_available_date"),
            "attrs": json.dumps(attributes, ensure_ascii=False, default=str),
            "images": json.dumps(item.get("image_urls") or [], ensure_ascii=False),
            "bullets": json.dumps(item.get("bullet_points") or [], ensure_ascii=False),
            "raw": json.dumps({**item, "authorization_reference": source.get("authorization_reference")},
                              ensure_ascii=False, default=str),
        }
        existing_id = await session.scalar(text("""
            SELECT id FROM market_listings
             WHERE tenant_id=:tenant AND dataset_id=:dataset AND platform_listing_id=:platform_id
             ORDER BY captured_at DESC,id DESC LIMIT 1
        """), params)
        if existing_id:
            params["listing"] = int(existing_id)
            await session.execute(text("""
                UPDATE market_listings
                   SET listing_url=:url,title=:title,category_code=:category,currency=:currency,
                       list_price=:list_price,sale_price=:sale_price,brand=:brand,rating=:rating,
                       review_count=:review_count,captured_at=:captured,first_available_date=:first_available,
                       normalized_attributes=CAST(:attrs AS jsonb),image_urls=CAST(:images AS jsonb),
                       bullet_points=CAST(:bullets AS jsonb),raw_payload=CAST(:raw AS jsonb)
                 WHERE id=:listing AND tenant_id=:tenant AND dataset_id=:dataset
            """), params)
            return int(existing_id)
        return int(await session.scalar(text("""
            INSERT INTO market_listings
              (tenant_id,dataset_id,platform_listing_id,listing_url,title,category_code,currency,
               list_price,sale_price,brand,rating,review_count,captured_at,first_available_date,
               normalized_attributes,image_urls,bullet_points,raw_payload)
            VALUES (:tenant,:dataset,:platform_id,:url,:title,:category,:currency,:list_price,:sale_price,
                    :brand,:rating,:review_count,:captured,:first_available,CAST(:attrs AS jsonb),
                    CAST(:images AS jsonb),CAST(:bullets AS jsonb),CAST(:raw AS jsonb))
            RETURNING id
        """), params))

    async def _store_dataset_review(self, session: AsyncSession, *, tenant_id: int,
                                    source: dict[str, Any], item: dict[str, Any]) -> int:
        dataset_id = source.get("dataset_id")
        content = str(item.get("content_original") or item.get("content") or "").strip()
        asin = str(item.get("platform_listing_id") or item.get("asin") or "").strip().upper()
        if not dataset_id or not content or not asin:
            return 0
        listing_id = await session.scalar(text("""
            SELECT id FROM market_listings
             WHERE tenant_id=:tenant AND dataset_id=:dataset AND platform_listing_id=:asin
             ORDER BY captured_at DESC,id DESC LIMIT 1
        """), {"tenant": tenant_id, "dataset": int(dataset_id), "asin": asin})
        if not listing_id:
            listing_id = await self._upsert_dataset_listing(
                session, tenant_id=tenant_id, source=source,
                item={"platform_listing_id": asin, "title": item.get("listing_title")},
            )
        if not listing_id:
            return 0
        review_id = str(item.get("platform_review_id") or item.get("external_id") or "").strip()
        review_id = (review_id or f"crawl-{content_hash(content)[:24]}")[:200]
        reason = review_invalid_reason(content, set())
        is_valid = reason is None
        digest = content_hash(content) if is_valid else unique_invalid_hash(review_id, content)
        rating = _float(item.get("rating"))
        rating = rating if rating is None or 0 <= rating <= 5 else None
        sentiment = str(item.get("sentiment") or "").lower()
        if sentiment not in {"positive", "neutral", "negative"}:
            sentiment = infer_sentiment(content, rating)
        row = await session.scalar(text("""
            INSERT INTO reviews
              (tenant_id,dataset_id,listing_id,platform_review_id,rating,title_original,content_original,
               language_code,reviewer_location,sentiment,reviewed_at,verified_purchase,helpful_count,
               is_valid,invalid_reason,content_hash)
            VALUES (:tenant,:dataset,:listing,:review_id,:rating,:title,:content,:language,:location,
                    :sentiment,:reviewed,:verified,:helpful,:is_valid,:invalid_reason,:hash)
            ON CONFLICT DO NOTHING RETURNING id
        """), {
            "tenant": tenant_id, "dataset": int(dataset_id), "listing": int(listing_id),
            "review_id": review_id, "rating": rating, "title": item.get("title_original"),
            "content": content, "language": (item.get("language_code") or "en")[:16],
            "location": item.get("reviewer_location") or item.get("user_location"),
            "sentiment": sentiment, "reviewed": _parse_datetime(item.get("reviewed_at") or item.get("created_at")),
            "verified": bool(item.get("verified_purchase", False)),
            "helpful": max(0, _int(item.get("helpful_count")) or 0), "is_valid": is_valid,
            "invalid_reason": None if is_valid else REASON_LABELS.get(reason, reason), "hash": digest,
        })
        return 1 if row else 0

    async def _refresh_bound_dataset(self, session: AsyncSession, *, tenant_id: int,
                                     dataset_id: int, source: dict[str, Any]) -> None:
        stats = (await session.execute(text("""
            SELECT count(DISTINCT l.platform_listing_id) AS listings,
                   count(r.id) AS reviews,
                   count(r.id) FILTER (WHERE r.is_valid) AS valid_reviews
              FROM market_listings l
              LEFT JOIN reviews r ON r.listing_id=l.id AND r.dataset_id=l.dataset_id AND r.tenant_id=l.tenant_id
             WHERE l.tenant_id=:tenant AND l.dataset_id=:dataset
        """), {"tenant": tenant_id, "dataset": dataset_id})).mappings().one()
        listings = int(stats["listings"] or 0)
        reviews = int(stats["reviews"] or 0)
        valid = int(stats["valid_reviews"] or 0)
        quality = min(100, round(20 + (valid / reviews if reviews else 1) * 80)) if listings else 0
        live_report = {
            "source_id": source.get("source_id"),
            "source_kind": source.get("source_kind"),
            "last_synced_at": _now().isoformat(),
            "listing_count": listings,
            "review_count": reviews,
            "valid_review_count": valid,
            "filtered_review_count": max(0, reviews - valid),
            "mode": "incremental_upsert",
        }
        await session.execute(text("""
            UPDATE market_datasets
               SET status='ready',listing_count=:listings,review_count=:reviews,
                   valid_review_count=:valid,quality_score=:quality,
                   quality_report=COALESCE(quality_report,'{}'::jsonb)
                     || jsonb_build_object('live_collection',CAST(:live_report AS jsonb)),
                   updated_at=CURRENT_TIMESTAMP
             WHERE id=:dataset AND tenant_id=:tenant AND deleted_at IS NULL
        """), {"tenant": tenant_id, "dataset": dataset_id, "listings": listings,
                 "reviews": reviews, "valid": valid, "quality": quality,
                 "live_report": json.dumps(live_report, ensure_ascii=False)})

    def _classify_sentiment(self, rating: float | None, content: str) -> tuple[str, float]:
        lowered = content.lower()
        if any(term in lowered for term in NEGATIVE_TERMS):
            return "negative", 0.9
        if any(term in lowered for term in POSITIVE_TERMS):
            return "positive", 0.85
        if rating is not None:
            if rating >= 4:
                return "positive", 0.75
            if rating <= 2:
                return "negative", 0.75
        return "neutral", 0.5

    async def ingest_sentiment_events(self, session: AsyncSession, *, tenant_id: int,
                                      events: list[dict[str, Any]], source_id: int | None,
                                      authorization_reference: str | None,
                                      defaults: dict[str, Any] | None = None) -> dict[str, Any]:
        if source_id is not None:
            source = await self.get_source(session, tenant_id=tenant_id, source_id=source_id)
            authorization_reference = source["authorization_reference"]
        if not authorization_reference:
            raise BusinessError("AUTHORIZATION_REQUIRED", "舆情事件必须提供授权依据或绑定授权源", status_code=422)
        inserted = 0
        items: list[dict[str, Any]] = []
        for event in events:
            content = str(event.get("content_original") or event.get("content") or "").strip()
            if not content:
                continue
            external_id = (event.get("external_id") or event.get("platform_review_id") or "")[:200] or None
            reviewed_at = _parse_datetime(event.get("reviewed_at") or event.get("created_at"))
            rating = _float(event.get("rating"))
            sentiment, score = self._classify_sentiment(rating, content)
            content_hash = _sha256(json.dumps({
                "source": source_id, "external_id": external_id, "content": content,
                "reviewed_at": reviewed_at.isoformat() if reviewed_at else None,
            }, ensure_ascii=False, sort_keys=True))
            row = (await session.execute(text("""
                INSERT INTO sentiment_events
                  (tenant_id,source_id,external_id,platform,market_country,asin,reviewer_location,language_code,
                   rating,content_original,sentiment,sentiment_score,reviewed_at,content_hash,raw_payload)
                VALUES (:tenant,:source,:external,:platform,:country,:asin,:location,:language,:rating,:content,
                        :sentiment,:score,:reviewed,:hash,CAST(:raw AS jsonb))
                ON CONFLICT (tenant_id, content_hash) DO NOTHING
                RETURNING id AS event_id,received_at
            """), {
                "tenant": tenant_id, "source": source_id, "external": external_id,
                "platform": (event.get("platform") or (defaults or {}).get("platform") or "amazon")[:40],
                "country": (event.get("market_country") or (defaults or {}).get("market_country") or "US")[:2].upper(),
                "asin": (event.get("asin") or event.get("platform_listing_id") or "")[:40].upper() or None,
                "location": event.get("reviewer_location") or event.get("user_location"),
                "language": (event.get("language_code") or "")[:16] or None,
                "rating": rating, "content": content, "sentiment": sentiment, "score": score,
                "reviewed": reviewed_at, "hash": content_hash,
                "raw": json.dumps({**event, "authorization_reference": authorization_reference},
                                  ensure_ascii=False, default=str),
            })).mappings().one_or_none()
            if row:
                inserted += 1
                items.append({"event_id": int(row["event_id"]), "sentiment": sentiment,
                              "sentiment_score": score, "received_at": _jsonable(row["received_at"])})
        return {"inserted_count": inserted, "items": items}

    async def list_sentiment_events(self, session: AsyncSession, *, tenant_id: int,
                                    sentiment: str | None, market_country: str | None,
                                    query: str | None, limit: int) -> list[dict[str, Any]]:
        clauses = ["tenant_id=:tenant"]
        params: dict[str, Any] = {"tenant": tenant_id, "limit": limit}
        if sentiment:
            clauses.append("sentiment=:sentiment")
            params["sentiment"] = sentiment
        if market_country:
            clauses.append("market_country=:country")
            params["country"] = market_country.upper()
        if query:
            clauses.append("(content_original ILIKE :q OR asin ILIKE :q OR external_id ILIKE :q)")
            params["q"] = f"%{query}%"
        rows = (await session.execute(text(f"""
            SELECT id AS event_id,source_id,external_id,platform,market_country,asin,reviewer_location,
                   language_code,rating,content_original,sentiment,sentiment_score,reviewed_at,received_at
              FROM sentiment_events
             WHERE {' AND '.join(clauses)}
             ORDER BY received_at DESC,id DESC LIMIT :limit
        """), params)).mappings().all()
        return [{key: _jsonable(value) for key, value in dict(row).items()} for row in rows]

    async def list_sentiment_feed(self, session: AsyncSession, *, tenant_id: int,
                                  sentiment: str | None, market_country: str | None,
                                  query: str | None, dataset_id: int | None,
                                  origin: str, offset: int, limit: int, page: int) -> dict[str, Any]:
        clauses = ["1=1"]
        params: dict[str, Any] = {"tenant": tenant_id, "offset": offset, "limit": limit}
        if dataset_id:
            clauses.append("(origin <> 'dataset' OR dataset_id=:dataset)")
            params["dataset"] = dataset_id
        if market_country:
            clauses.append("market_country=:country")
            params["country"] = market_country.upper()
        if query:
            clauses.append("(content_original ILIKE :q OR COALESCE(asin,'') ILIKE :q)")
            params["q"] = f"%{query}%"
        if sentiment:
            clauses.append("sentiment=:sentiment")
            params["sentiment"] = sentiment
        if origin in {"live", "dataset"}:
            clauses.append("origin=:origin")
            params["origin"] = origin
        where = " AND ".join(clauses)
        feed_sql = """
            SELECT * FROM (
              SELECT 'live:' || e.id::text AS item_id, 'live' AS origin,
                     NULL::bigint AS dataset_id, NULL::text AS dataset_name,
                     e.asin, e.platform, e.market_country, e.rating::float8 AS rating,
                     e.content_original, e.sentiment, e.sentiment_score::float8 AS sentiment_score,
                     e.reviewer_location, TRUE AS is_valid,
                     COALESCE(e.reviewed_at, e.received_at) AS occurred_at
                FROM sentiment_events e
               WHERE e.tenant_id=:tenant
              UNION ALL
              SELECT 'review:' || r.id::text, 'dataset',
                     r.dataset_id, d.name,
                     l.platform_listing_id, d.platform, d.market_country, r.rating::float8,
                     r.content_original,
                     CASE
                       WHEN lower(COALESCE(r.sentiment,'')) IN ('positive','negative','neutral')
                         THEN lower(r.sentiment)
                       WHEN r.rating >= 4 THEN 'positive'
                       WHEN r.rating IS NOT NULL AND r.rating <= 2 THEN 'negative'
                       ELSE 'neutral'
                     END,
                     NULL::float8, r.reviewer_location, r.is_valid,
                     COALESCE(r.reviewed_at, r.created_at)
                FROM reviews r
                JOIN market_datasets d ON d.id=r.dataset_id AND d.tenant_id=r.tenant_id AND d.deleted_at IS NULL
                JOIN market_listings l ON l.id=r.listing_id
               WHERE r.tenant_id=:tenant AND r.is_valid
            ) feed
        """
        stats_params = {key: value for key, value in params.items() if key not in {"offset", "limit"}}
        stats = (await session.execute(text(f"""
            SELECT count(*) AS total,
                   count(*) FILTER (WHERE sentiment='positive') AS positive_count,
                   count(*) FILTER (WHERE sentiment='negative') AS negative_count,
                   count(*) FILTER (WHERE sentiment='neutral') AS neutral_count,
                   count(*) FILTER (WHERE origin='live') AS live_count,
                   count(*) FILTER (WHERE origin='dataset') AS dataset_count
              FROM ({feed_sql}) scoped
             WHERE {where}
        """), stats_params)).mappings().one()
        rows = (await session.execute(text(f"""
            SELECT item_id,origin,dataset_id,dataset_name,asin,platform,market_country,rating,
                   content_original,sentiment,sentiment_score,reviewer_location,is_valid,occurred_at
              FROM ({feed_sql}) scoped
             WHERE {where}
             ORDER BY occurred_at DESC NULLS LAST, item_id DESC
             OFFSET :offset LIMIT :limit
        """), params)).mappings().all()
        total = int(stats["total"] or 0)
        return {
            "items": [{key: _jsonable(value) for key, value in dict(row).items()} for row in rows],
            "total": total,
            "page": page,
            "page_size": limit,
            "has_next": page * limit < total,
            "positive_count": int(stats["positive_count"] or 0),
            "negative_count": int(stats["negative_count"] or 0),
            "neutral_count": int(stats["neutral_count"] or 0),
            "live_count": int(stats["live_count"] or 0),
            "dataset_count": int(stats["dataset_count"] or 0),
        }

