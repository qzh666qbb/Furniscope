def _now() -> datetime:
    return datetime.now(timezone.utc)


def _jsonable(value: Any) -> Any:
    if isinstance(value, datetime):
        return value.isoformat()
    if isinstance(value, Decimal):
        return float(value)
    return value


def _sha256(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def _safe_error(exc: Exception) -> str:
    if isinstance(exc, BusinessError):
        return exc.message[:300]
    return type(exc).__name__[:120]


def finalize_collect_run(*, status: str, fetched: int, inserted: int,
                         listing_asins: list[str], error_summary: str | None) -> tuple[str, str | None]:
    """Zero-result collects must not be recorded as succeeded."""
    if status != "succeeded":
        return status, error_summary
    wrote_anything = inserted > 0 or bool(listing_asins)
    if fetched <= 0 or not wrote_anything:
        return "failed", error_summary or "来源未返回可写入的竞品或评论，零结果不记为成功"
    return status, error_summary


def _parse_datetime(value: Any) -> datetime | None:
    if value in (None, ""):
        return None
    if isinstance(value, datetime):
        return value if value.tzinfo else value.replace(tzinfo=timezone.utc)
    try:
        parsed = datetime.fromisoformat(str(value).replace("Z", "+00:00"))
    except ValueError:
        return None
    return parsed if parsed.tzinfo else parsed.replace(tzinfo=timezone.utc)


def _float(value: Any) -> float | None:
    try:
        return None if value in (None, "") else float(value)
    except (TypeError, ValueError):
        return None


def _int(value: Any) -> int | None:
    try:
        return None if value in (None, "") else int(float(value))
    except (TypeError, ValueError):
        return None


def _local_name(tag: str) -> str:
    return tag.rsplit("}", 1)[-1].lower()


def _child_text(element: ET.Element, names: set[str]) -> str | None:
    for child in list(element):
        if _local_name(child.tag) in names:
            if _local_name(child.tag) == "link" and child.attrib.get("href"):
                return child.attrib["href"]
            if child.text and child.text.strip():
                return child.text.strip()
    return None


