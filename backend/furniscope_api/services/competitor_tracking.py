    async def list_alerts(self, session: AsyncSession, *, tenant_id: int, limit: int = 50,
                          unread_only: bool = False) -> list[dict[str, Any]]:
        filters = "a.tenant_id=:tenant AND w.status='active'"
        if unread_only:
            filters += " AND a.is_read=FALSE"
        rows = (await session.execute(text(f"""
            SELECT a.id AS alert_id,a.watch_id,a.asin,a.change_type,a.summary,a.before_value,a.after_value,
                   a.captured_at,a.is_read,w.title
              FROM competitor_change_alerts a
              JOIN competitor_watch_targets w ON w.id=a.watch_id
             WHERE {filters}
             ORDER BY a.captured_at DESC,a.id DESC LIMIT :limit
        """), {"tenant": tenant_id, "limit": limit})).mappings().all()
        items = []
        for row in rows:
            item = {key: _jsonable(value) if key not in {"before_value", "after_value"} else value
                    for key, value in dict(row).items()}
            item["change_label"] = CHANGE_LABELS.get(item["change_type"], item["change_type"])
            items.append(item)
        return items

