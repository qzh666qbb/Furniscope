    async def rhythm(self, session: AsyncSession, *, tenant_id: int) -> dict[str, Any]:
        dataset_ids = (await session.execute(text("""
            SELECT DISTINCT dataset_id FROM competitor_watch_targets
             WHERE tenant_id=:tenant AND status='active' AND dataset_id IS NOT NULL
        """), {"tenant": tenant_id})).scalars().all()
        if not dataset_ids:
            ready = (await session.execute(text("""
                SELECT id FROM market_datasets
                 WHERE tenant_id=:tenant AND deleted_at IS NULL AND status='ready'
                 ORDER BY updated_at DESC LIMIT 1
            """), {"tenant": tenant_id})).scalar()
            dataset_ids = [ready] if ready else []
        if not dataset_ids:
            return {"launches": [], "promos": []}
        launches = (await session.execute(text("""
            SELECT to_char(date_trunc('month', COALESCE(first_available_date, captured_at::date)), 'YYYY-MM') AS month,
                   count(*) AS listing_count
              FROM market_listings
             WHERE tenant_id=:tenant AND dataset_id = ANY(CAST(:datasets AS bigint[]))
             GROUP BY 1 ORDER BY 1 DESC LIMIT 12
        """), {"tenant": tenant_id, "datasets": list(dataset_ids)})).mappings().all()
        promos = (await session.execute(text("""
            SELECT to_char(date_trunc('month', captured_at), 'YYYY-MM') AS month,
                   count(*) FILTER (WHERE list_price IS NOT NULL AND list_price > sale_price) AS promo_count,
                   count(*) AS listing_count
              FROM market_listings
             WHERE tenant_id=:tenant AND dataset_id = ANY(CAST(:datasets AS bigint[]))
             GROUP BY 1 ORDER BY 1 DESC LIMIT 12
        """), {"tenant": tenant_id, "datasets": list(dataset_ids)})).mappings().all()
        return {
            "launches": [dict(row) for row in launches],
            "promos": [dict(row) for row in promos],
        }

    def _row_payload(self, row: dict[str, Any]) -> dict[str, Any]:
        images = row.get("image_urls") or []
        bullets = row.get("bullet_points") or []
        if isinstance(images, str):
            images = json.loads(images)
        if isinstance(bullets, str):
            bullets = json.loads(bullets)
        payload = {
            "asin": str(row.get("asin") or row.get("platform_listing_id") or "").upper(),
            "title": row.get("title"),
            "sale_price": row.get("sale_price"),
            "list_price": row.get("list_price"),
            "currency": row.get("currency"),
            "rating": row.get("rating"),
            "review_count": row.get("review_count"),
            "image_urls": images,
            "bullet_points": bullets,
            "promo_label": promo_label(row.get("sale_price"), row.get("list_price"), row.get("coupon_value")),
            "first_available_date": row.get("first_available_date"),
            "captured_at": row.get("captured_at") or _now(),
            "market_country": row.get("market_country"),
            "platform": row.get("platform"),
            "dataset_id": row.get("dataset_id"),
        }
        payload["fingerprint"] = listing_fingerprint(payload)
        return payload

    async def _find_listing(self, session: AsyncSession, *, tenant_id: int, asin: str,
                            dataset_id: int | None, market_country: str | None) -> dict[str, Any] | None:
        params: dict[str, Any] = {"tenant": tenant_id, "asin": asin}
        extra = ""
        if dataset_id:
            extra += " AND l.dataset_id=:dataset"
            params["dataset"] = dataset_id
        if market_country:
            extra += " AND d.market_country=:country"
            params["country"] = market_country
        row = (await session.execute(text(f"""
            SELECT l.platform_listing_id AS asin,l.title,l.sale_price,l.list_price,l.currency,l.rating,
                   l.review_count,l.image_urls,l.bullet_points,l.coupon_value,l.first_available_date,
                   l.captured_at,l.dataset_id,d.market_country,d.platform
              FROM market_listings l
              JOIN market_datasets d ON d.id=l.dataset_id AND d.tenant_id=l.tenant_id
             WHERE l.tenant_id=:tenant AND upper(l.platform_listing_id)=:asin {extra}
               AND d.deleted_at IS NULL
             ORDER BY l.captured_at DESC,l.id DESC LIMIT 1
        """), params)).mappings().one_or_none()
        return dict(row) if row else None

    async def _own_catalog(self, session: AsyncSession, *, tenant_id: int) -> list[dict[str, Any]]:
        rows = (await session.execute(text("""
            SELECT sku, name FROM products WHERE tenant_id=:tenant AND deleted_at IS NULL
        """), {"tenant": tenant_id})).mappings().all()
        return [dict(row) for row in rows]

    def _listing_is_own(self, catalog: list[dict[str, Any]], asin: Any, title: Any) -> bool:
        listing_id = str(asin or "").strip().upper()
        if not listing_id:
            return False
        for product in catalog:
            sku = str(product.get("sku") or "").strip().upper()
            if sku and listing_id == sku:
                return True
        return False

    async def _is_own_listing(self, session: AsyncSession, *, tenant_id: int, asin: str,
                              title: str | None) -> bool:
        catalog = await self._own_catalog(session, tenant_id=tenant_id)
        return self._listing_is_own(catalog, asin, title)

