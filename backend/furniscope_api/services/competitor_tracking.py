ASIN_PATTERN = re.compile(r"^[A-Z0-9][A-Z0-9\-_.]{3,39}$", re.I)
TOKEN_PATTERN = re.compile(r"[a-z0-9]+|[\u4e00-\u9fff]")
CHANGE_LABELS = {
    "price": "价格变动",
    "title": "标题更新",
    "image": "主图更新",
    "bullets": "五点描述更新",
    "promo": "促销变动",
    "new_listing": "监控目标上新",
}


def _text_similarity(left: str, right: str) -> float:
    a = set(TOKEN_PATTERN.findall((left or "").lower()))
    b = set(TOKEN_PATTERN.findall((right or "").lower()))
    return len(a & b) / len(a | b) if a and b else 0.0


def _now() -> datetime:
    return datetime.now(timezone.utc)


def _jsonable(value: Any) -> Any:
    if isinstance(value, datetime):
        return value.isoformat()
    if isinstance(value, Decimal):
        return float(value)
    return value


def promo_label(sale_price: Any, list_price: Any, coupon: Any = None) -> str | None:
    if coupon not in (None, "", [], {}):
        return str(coupon)[:120]
    try:
        sale = None if sale_price in (None, "") else float(sale_price)
        listed = None if list_price in (None, "") else float(list_price)
    except (TypeError, ValueError):
        return None
    if sale is None or listed is None or listed <= sale or listed <= 0:
        return None
    off = round((1 - sale / listed) * 100)
    return f"直降 {off}%"


def listing_fingerprint(payload: dict[str, Any]) -> str:
    material = json.dumps({
        "title": payload.get("title") or "",
        "sale_price": _jsonable(payload.get("sale_price")),
        "list_price": _jsonable(payload.get("list_price")),
        "image_urls": payload.get("image_urls") or [],
        "bullet_points": payload.get("bullet_points") or [],
        "promo_label": payload.get("promo_label") or "",
    }, ensure_ascii=False, sort_keys=True, default=str)
    return hashlib.sha256(material.encode("utf-8")).hexdigest()


def diff_snapshots(previous: dict[str, Any], current: dict[str, Any]) -> list[dict[str, Any]]:
    changes: list[dict[str, Any]] = []
    prev_sale = previous.get("sale_price")
    curr_sale = current.get("sale_price")
    if _jsonable(prev_sale) != _jsonable(curr_sale):
        changes.append({
            "change_type": "price",
            "summary": f"售价 {prev_sale} → {curr_sale}",
            "before_value": prev_sale, "after_value": curr_sale,
        })
    if (previous.get("title") or "") != (current.get("title") or ""):
        changes.append({
            "change_type": "title",
            "summary": "Listing 标题已更新",
            "before_value": previous.get("title"), "after_value": current.get("title"),
        })
    if json.dumps(previous.get("image_urls") or [], sort_keys=True) != json.dumps(current.get("image_urls") or [], sort_keys=True):
        changes.append({
            "change_type": "image",
            "summary": "主图或图片组已更新",
            "before_value": previous.get("image_urls") or [],
            "after_value": current.get("image_urls") or [],
        })
    if json.dumps(previous.get("bullet_points") or [], sort_keys=True) != json.dumps(current.get("bullet_points") or [], sort_keys=True):
        changes.append({
            "change_type": "bullets",
            "summary": "五点描述已更新",
            "before_value": previous.get("bullet_points") or [],
            "after_value": current.get("bullet_points") or [],
        })
    if (previous.get("promo_label") or "") != (current.get("promo_label") or ""):
        changes.append({
            "change_type": "promo",
            "summary": f"促销 {previous.get('promo_label') or '无'} → {current.get('promo_label') or '无'}",
            "before_value": previous.get("promo_label"),
            "after_value": current.get("promo_label"),
        })
    return changes


