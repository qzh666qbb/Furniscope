CREATE OR REPLACE FUNCTION assign_default_role_to_user()
RETURNS trigger LANGUAGE plpgsql
SET search_path TO furniscope,public AS $$
DECLARE selected_role_id bigint;
BEGIN
  IF NEW.role_code<>'user' THEN
    RETURN NEW;
  END IF;
  SELECT id INTO selected_role_id FROM tenant_roles
   WHERE tenant_id=NEW.tenant_id
     AND role_code=CASE
       WHEN EXISTS(
         SELECT FROM user_role_assignments a
         JOIN tenant_roles r ON r.id=a.role_id AND r.tenant_id=a.tenant_id
        WHERE a.tenant_id=NEW.tenant_id AND r.role_code='tenant_owner'
       ) THEN 'viewer' ELSE 'tenant_owner' END;
  IF selected_role_id IS NOT NULL THEN
    INSERT INTO user_role_assignments(tenant_id,user_id,role_id)
    VALUES(NEW.tenant_id,NEW.id,selected_role_id)
    ON CONFLICT DO NOTHING;
  END IF;
  RETURN NEW;
END $$;
