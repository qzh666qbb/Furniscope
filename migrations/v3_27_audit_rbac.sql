CREATE OR REPLACE FUNCTION audit_event_hash(
  event_uuid UUID,
  tenant_id BIGINT,
  chain_sequence BIGINT,
  previous_hash TEXT,
  actor_user_id BIGINT,
  action_code TEXT,
  resource_type TEXT,
  resource_id BIGINT,
  request_id TEXT,
  before_snapshot JSONB,
  after_snapshot JSONB,
  ip_address TEXT,
  user_agent TEXT,
  occurred_at TIMESTAMPTZ
) RETURNS CHAR(64)
LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
  SELECT encode(digest(convert_to(jsonb_build_object(
    'event_uuid',event_uuid::text,
    'tenant_id',tenant_id,
    'chain_sequence',chain_sequence,
    'previous_hash',previous_hash,
    'actor_user_id',actor_user_id,
    'action_code',action_code,
    'resource_type',resource_type,
    'resource_id',resource_id,
    'request_id',request_id,
    'before_snapshot',before_snapshot,
    'after_snapshot',after_snapshot,
    'ip_address',ip_address,
    'user_agent',user_agent,
    'occurred_at',to_char(occurred_at AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.US"Z"')
  )::text,'UTF8'),'sha256'),'hex')::char(64)
$$;

DO $$
DECLARE audit_record record;
DECLARE next_sequence bigint;
DECLARE prior_hash char(64);
DECLARE calculated_hash char(64);
BEGIN
  FOR audit_record IN
    SELECT * FROM audit_logs
     WHERE chain_sequence IS NULL
     ORDER BY COALESCE(tenant_id,0),occurred_at,id FOR UPDATE
  LOOP
    SELECT COALESCE(max(chain_sequence),0)+1,event_hash
      INTO next_sequence,prior_hash
      FROM audit_logs
     WHERE COALESCE(tenant_id,0)=COALESCE(audit_record.tenant_id,0)
       AND chain_sequence IS NOT NULL
     GROUP BY event_hash,chain_sequence
     ORDER BY chain_sequence DESC LIMIT 1;
    next_sequence:=COALESCE(next_sequence,1);
    prior_hash:=COALESCE(prior_hash,repeat('0',64)::char(64));
    audit_record.event_uuid:=COALESCE(audit_record.event_uuid,gen_random_uuid());
    calculated_hash:=audit_event_hash(
      audit_record.event_uuid,audit_record.tenant_id,next_sequence,prior_hash,
      audit_record.actor_user_id,audit_record.action_code,audit_record.resource_type,
      audit_record.resource_id,audit_record.request_id,audit_record.before_snapshot,
      audit_record.after_snapshot,audit_record.ip_address,audit_record.user_agent,
      audit_record.occurred_at
    );
    UPDATE audit_logs SET event_uuid=audit_record.event_uuid,
      chain_sequence=next_sequence,previous_hash=prior_hash,event_hash=calculated_hash
     WHERE id=audit_record.id;
  END LOOP;
END $$;

CREATE OR REPLACE FUNCTION prepare_audit_chain()
RETURNS trigger LANGUAGE plpgsql
SET search_path TO furniscope,public AS $$
DECLARE prior audit_logs%ROWTYPE;
DECLARE chain_key bigint:=COALESCE(NEW.tenant_id,0);
BEGIN
  PERFORM pg_advisory_xact_lock(hashtextextended('furniscope.audit.'||chain_key::text,0));
  SELECT * INTO prior FROM audit_logs
   WHERE COALESCE(tenant_id,0)=chain_key
   ORDER BY chain_sequence DESC LIMIT 1;
  NEW.event_uuid:=COALESCE(NEW.event_uuid,gen_random_uuid());
  NEW.occurred_at:=COALESCE(NEW.occurred_at,CURRENT_TIMESTAMP);
  NEW.chain_sequence:=COALESCE(prior.chain_sequence,0)+1;
  NEW.previous_hash:=COALESCE(prior.event_hash,repeat('0',64)::char(64));
  NEW.event_hash:=audit_event_hash(
    NEW.event_uuid,NEW.tenant_id,NEW.chain_sequence,NEW.previous_hash,
    NEW.actor_user_id,NEW.action_code,NEW.resource_type,NEW.resource_id,
    NEW.request_id,NEW.before_snapshot,NEW.after_snapshot,NEW.ip_address,
    NEW.user_agent,NEW.occurred_at
  );
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_audit_chain_insert ON audit_logs;
CREATE TRIGGER trg_audit_chain_insert
BEFORE INSERT ON audit_logs FOR EACH ROW EXECUTE FUNCTION prepare_audit_chain();

CREATE OR REPLACE FUNCTION protect_audit_chain()
RETURNS trigger LANGUAGE plpgsql
SET search_path TO furniscope,public AS $$
DECLARE table_owner text;
BEGIN
  SELECT owner.rolname INTO table_owner
    FROM pg_class c
    JOIN pg_namespace n ON n.oid=c.relnamespace
    JOIN pg_roles owner ON owner.oid=c.relowner
   WHERE n.nspname=TG_TABLE_SCHEMA AND c.relname=TG_TABLE_NAME;
  IF session_user=table_owner
     OR pg_has_role(session_user,'furniscope_migrator','MEMBER')
     OR pg_has_role(session_user,'furniscope_schema_owner','MEMBER') THEN
    RETURN CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END;
  END IF;
  RAISE EXCEPTION 'audit chain is append-only' USING ERRCODE='42501';
END $$;
DROP TRIGGER IF EXISTS trg_audit_chain_protect ON audit_logs;
CREATE TRIGGER trg_audit_chain_protect
BEFORE UPDATE OR DELETE ON audit_logs FOR EACH ROW EXECUTE FUNCTION protect_audit_chain();

