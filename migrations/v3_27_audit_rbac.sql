CREATE OR REPLACE FUNCTION seed_tenant_builtin_roles(target_tenant_id BIGINT)
RETURNS void LANGUAGE plpgsql
SET search_path TO furniscope,public AS $$
DECLARE role_spec record;
DECLARE permission text;
DECLARE target_role_id bigint;
BEGIN
  FOR role_spec IN
    SELECT * FROM (VALUES
      ('tenant_owner','企业所有者','企业全权限与成员管理',
       ARRAY['tenant.members.manage','tenant.settings.write','product.read','product.write',
             'dataset.read','dataset.write','forecast.read','forecast.train','forecast.publish',
             'analysis.read','analysis.execute','knowledge.read','knowledge.write',
             'memory.read','memory.write','audit.read']::text[]),
      ('data_admin','数据管理员','维护企业数据、知识和记忆',
       ARRAY['product.read','product.write','dataset.read','dataset.write','forecast.read',
             'forecast.train','analysis.read','analysis.execute','knowledge.read',
             'knowledge.write','memory.read','memory.write','audit.read']::text[]),
      ('analyst','分析师','执行分析与训练并维护业务事实',
       ARRAY['product.read','product.write','dataset.read','dataset.write','forecast.read',
             'forecast.train','analysis.read','analysis.execute','knowledge.read',
             'knowledge.write','memory.read','memory.write']::text[]),
      ('operator','运营人员','维护产品数据并执行分析',
       ARRAY['product.read','product.write','dataset.read','dataset.write','forecast.read',
             'analysis.read','analysis.execute','knowledge.read','memory.read']::text[]),
      ('auditor','审计员','只读业务数据和审计记录',
       ARRAY['product.read','dataset.read','forecast.read','analysis.read','knowledge.read',
             'memory.read','audit.read']::text[]),
      ('viewer','访客','只读企业业务数据',
       ARRAY['product.read','dataset.read','forecast.read','analysis.read','knowledge.read',
             'memory.read']::text[])
    ) AS roles(role_code,display_name,description,permissions)
  LOOP
    INSERT INTO tenant_roles(tenant_id,role_code,display_name,description,built_in)
    VALUES(target_tenant_id,role_spec.role_code,role_spec.display_name,role_spec.description,true)
    ON CONFLICT(tenant_id,role_code) DO UPDATE
      SET display_name=EXCLUDED.display_name,description=EXCLUDED.description,built_in=true
    RETURNING id INTO target_role_id;
    FOREACH permission IN ARRAY role_spec.permissions LOOP
      INSERT INTO role_permissions(tenant_id,role_id,permission_code)
      VALUES(target_tenant_id,target_role_id,permission)
      ON CONFLICT DO NOTHING;
    END LOOP;
  END LOOP;
END $$;

DO $$
DECLARE tenant_record record;
DECLARE owner_user_id bigint;
DECLARE owner_role_id bigint;
DECLARE user_record record;
DECLARE viewer_role_id bigint;
BEGIN
  FOR tenant_record IN SELECT id FROM tenants ORDER BY id LOOP
    PERFORM seed_tenant_builtin_roles(tenant_record.id);
    SELECT id INTO owner_role_id FROM tenant_roles
     WHERE tenant_id=tenant_record.id AND role_code='tenant_owner';
    SELECT id INTO viewer_role_id FROM tenant_roles
     WHERE tenant_id=tenant_record.id AND role_code='viewer';
    SELECT id INTO owner_user_id FROM users
     WHERE tenant_id=tenant_record.id AND role_code='user'
     ORDER BY created_at,id LIMIT 1;
    IF owner_user_id IS NOT NULL THEN
      INSERT INTO user_role_assignments(tenant_id,user_id,role_id)
      VALUES(tenant_record.id,owner_user_id,owner_role_id)
      ON CONFLICT DO NOTHING;
    END IF;
    FOR user_record IN
      SELECT id FROM users
       WHERE tenant_id=tenant_record.id AND role_code='user' AND id<>owner_user_id
    LOOP
      INSERT INTO user_role_assignments(tenant_id,user_id,role_id)
      VALUES(tenant_record.id,user_record.id,viewer_role_id)
      ON CONFLICT DO NOTHING;
    END LOOP;
  END LOOP;
END $$;

