EXCEPTION WHEN duplicate_object THEN NULL; END $$;

WITH ranked AS (
  SELECT id,row_number() OVER(
    PARTITION BY tenant_id,scope,user_id,workspace_id,memory_key
    ORDER BY updated_at DESC,id DESC
  ) AS position
  FROM customer_memories WHERE status='confirmed'
)
UPDATE customer_memories m
   SET status='archived',archived_at=COALESCE(m.archived_at,CURRENT_TIMESTAMP)
  FROM ranked r WHERE r.id=m.id AND r.position>1;
CREATE UNIQUE INDEX IF NOT EXISTS uk_customer_memory_confirmed_workspace
  ON customer_memories(tenant_id,user_id,workspace_id,memory_key)
  WHERE status='confirmed' AND scope='workspace';
