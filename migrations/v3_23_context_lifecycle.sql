  tenant_id BIGINT NOT NULL,
  workspace_id BIGINT NOT NULL,
  client_turn_id UUID NOT NULL,
  idempotency_key VARCHAR(128) NOT NULL,
  request_hash CHAR(64) NOT NULL,
  task_id BIGINT,
  regenerated_from_turn_uuid UUID,
  user_message_uuid UUID,
  assistant_message_uuid UUID,
  status VARCHAR(16) NOT NULL DEFAULT 'pending',
  request_payload JSONB NOT NULL DEFAULT '{}'::jsonb,
  response_payload JSONB,
  error_code VARCHAR(64),
  created_by BIGINT NOT NULL,
  started_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  completed_at TIMESTAMPTZ(3),
  cancelled_at TIMESTAMPTZ(3),
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(tenant_id,workspace_id,client_turn_id),
  UNIQUE(tenant_id,workspace_id,idempotency_key),
  UNIQUE(id,tenant_id),
  UNIQUE(turn_uuid,tenant_id),
  FOREIGN KEY(tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
  FOREIGN KEY(workspace_id,tenant_id) REFERENCES analysis_workspaces(id,tenant_id) ON DELETE CASCADE,
  FOREIGN KEY(task_id,tenant_id) REFERENCES analysis_tasks(id,tenant_id),
  FOREIGN KEY(created_by,tenant_id) REFERENCES users(id,tenant_id),
  FOREIGN KEY(regenerated_from_turn_uuid) REFERENCES analysis_workspace_turns(turn_uuid),
  FOREIGN KEY(user_message_uuid) REFERENCES analysis_workspace_messages(message_uuid) ON DELETE SET NULL,
  FOREIGN KEY(assistant_message_uuid) REFERENCES analysis_workspace_messages(message_uuid) ON DELETE SET NULL,
  CHECK(status IN ('pending','completed','failed','cancelled')),
  CHECK(jsonb_typeof(request_payload)='object'),
  CHECK(response_payload IS NULL OR jsonb_typeof(response_payload)='object'),
  CHECK(
    (status='pending' AND completed_at IS NULL AND cancelled_at IS NULL) OR
    (status='completed' AND completed_at IS NOT NULL AND cancelled_at IS NULL) OR
    (status='failed' AND completed_at IS NOT NULL AND cancelled_at IS NULL) OR
    (status='cancelled' AND cancelled_at IS NOT NULL)
  )
);
