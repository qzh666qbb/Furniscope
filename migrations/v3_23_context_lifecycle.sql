  ON customer_memories(tenant_id,user_id,memory_key)
  WHERE status='confirmed' AND scope='user';
CREATE UNIQUE INDEX IF NOT EXISTS uk_customer_memory_confirmed_tenant
  ON customer_memories(tenant_id,memory_key)
