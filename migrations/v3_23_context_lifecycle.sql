  ADD COLUMN IF NOT EXISTS memory_type VARCHAR(64) GENERATED ALWAYS AS (memory_key) STORED;
ALTER TABLE customer_memories ADD COLUMN IF NOT EXISTS scope VARCHAR(16) NOT NULL DEFAULT 'user';
UPDATE customer_memories SET scope=CASE WHEN workspace_id IS NULL THEN 'user' ELSE 'workspace' END;
ALTER TABLE customer_memories ADD COLUMN IF NOT EXISTS supersedes_memory_uuid UUID;
