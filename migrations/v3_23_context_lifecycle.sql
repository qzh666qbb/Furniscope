CREATE TABLE IF NOT EXISTS knowledge_chunks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chunk_uuid UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  tenant_id BIGINT NOT NULL,
  document_id BIGINT NOT NULL,
  document_version_id BIGINT NOT NULL,
  chunk_index INTEGER NOT NULL,
  page INTEGER,
  chunk_text TEXT NOT NULL,
  token_estimate INTEGER NOT NULL,
  embedding JSONB,
  search_vector TSVECTOR GENERATED ALWAYS AS (to_tsvector('simple',chunk_text)) STORED,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(tenant_id,document_version_id,chunk_index),
  UNIQUE(id,tenant_id),
  FOREIGN KEY(tenant_id) REFERENCES tenants(id) ON DELETE CASCADE,
  FOREIGN KEY(document_id,tenant_id) REFERENCES knowledge_documents(id,tenant_id) ON DELETE CASCADE,
  FOREIGN KEY(document_version_id,tenant_id)
    REFERENCES knowledge_document_versions(id,tenant_id) ON DELETE CASCADE,
  CHECK(chunk_index>=0),
  CHECK(page IS NULL OR page>0),
  CHECK(char_length(chunk_text)>0),
  CHECK(token_estimate>0),
  CHECK(embedding IS NULL OR jsonb_typeof(embedding)='array')
);
CREATE INDEX IF NOT EXISTS idx_knowledge_chunks_search
  ON knowledge_chunks USING GIN(search_vector);

