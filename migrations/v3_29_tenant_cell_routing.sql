CREATE TABLE IF NOT EXISTS deployment_cells (
  cell_code VARCHAR(64) PRIMARY KEY,
  display_name VARCHAR(160) NOT NULL,
  region_code VARCHAR(64) NOT NULL,
  cell_kind VARCHAR(16) NOT NULL DEFAULT 'shared',
  status VARCHAR(16) NOT NULL DEFAULT 'active',
  is_default BOOLEAN NOT NULL DEFAULT false,
  routing_endpoint VARCHAR(500),
  database_secret_ref VARCHAR(500),
  capacity_tenants INTEGER,
  safe_metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_deployment_cell_code CHECK(cell_code ~ '^[a-z][a-z0-9-]{1,63}$'),
  CONSTRAINT chk_deployment_cell_region CHECK(region_code ~ '^[a-z][a-z0-9-]{1,63}$'),
  CONSTRAINT chk_deployment_cell_kind CHECK(cell_kind IN ('shared','dedicated')),
  CONSTRAINT chk_deployment_cell_status CHECK(
    status IN ('provisioning','active','draining','offline')
  ),
  CONSTRAINT chk_deployment_cell_capacity CHECK(
    capacity_tenants IS NULL OR capacity_tenants>0
  ),
  CONSTRAINT chk_deployment_cell_metadata CHECK(jsonb_typeof(safe_metadata)='object')
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_deployment_cell_default
  ON deployment_cells(is_default) WHERE is_default;
COMMENT ON TABLE deployment_cells IS
  'Credential-free control-plane directory. database_secret_ref names a secret; it never stores credentials.';

