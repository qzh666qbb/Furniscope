) ON CONFLICT(cell_code) DO NOTHING;

CREATE TABLE IF NOT EXISTS tenant_placements (
  tenant_id BIGINT PRIMARY KEY REFERENCES tenants(id) ON DELETE CASCADE,
  cell_code VARCHAR(64) NOT NULL REFERENCES deployment_cells(cell_code),
  residency_region VARCHAR(64) NOT NULL,
  service_tier VARCHAR(24) NOT NULL DEFAULT 'standard',
  status VARCHAR(16) NOT NULL DEFAULT 'active',
  placement_version BIGINT NOT NULL DEFAULT 1,
  routing_generation BIGINT NOT NULL DEFAULT 1,
  migration_uuid UUID,
  placed_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_tenant_placement_boundary UNIQUE(tenant_id,cell_code),
  CONSTRAINT chk_tenant_placement_region CHECK(
    residency_region ~ '^[a-z][a-z0-9-]{1,63}$'
  ),
  CONSTRAINT chk_tenant_placement_tier CHECK(
    service_tier IN ('standard','priority','dedicated','regulated')
  ),
  CONSTRAINT chk_tenant_placement_status CHECK(
    status IN ('active','migrating','frozen','validating','cutover','failed')
  ),
  CONSTRAINT chk_tenant_placement_versions CHECK(
    placement_version>0 AND routing_generation>0
  ),
  CONSTRAINT chk_tenant_placement_migration CHECK(
    (status='active' AND migration_uuid IS NULL)
    OR (status<>'active' AND migration_uuid IS NOT NULL)
  )
);
CREATE INDEX IF NOT EXISTS idx_tenant_placements_route
  ON tenant_placements(cell_code,status,tenant_id);

CREATE TABLE IF NOT EXISTS tenant_migration_jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  migration_uuid UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  tenant_id BIGINT NOT NULL REFERENCES tenants(id),
  source_cell_code VARCHAR(64) NOT NULL REFERENCES deployment_cells(cell_code),
  target_cell_code VARCHAR(64) NOT NULL REFERENCES deployment_cells(cell_code),
  status VARCHAR(20) NOT NULL DEFAULT 'planned',
  requested_by BIGINT REFERENCES users(id),
  package_sha256 CHAR(64),
  source_row_counts JSONB NOT NULL DEFAULT '{}'::jsonb,
  target_row_counts JSONB NOT NULL DEFAULT '{}'::jsonb,
  validation_hash CHAR(64),
  failure_code VARCHAR(100),
  failure_detail VARCHAR(2000),
  planned_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  frozen_at TIMESTAMPTZ(3),
  exported_at TIMESTAMPTZ(3),
  restored_at TIMESTAMPTZ(3),
  validated_at TIMESTAMPTZ(3),
  cutover_at TIMESTAMPTZ(3),
  completed_at TIMESTAMPTZ(3),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_tenant_migration_boundary UNIQUE(id,tenant_id),
  CONSTRAINT chk_tenant_migration_cells CHECK(source_cell_code<>target_cell_code),
  CONSTRAINT chk_tenant_migration_status CHECK(
    status IN (
      'planned','freezing','exporting','restoring','validating',
      'cutover','completed','failed','rolled_back'
    )
  ),
  CONSTRAINT chk_tenant_migration_hashes CHECK(
    (package_sha256 IS NULL OR package_sha256 ~ '^[0-9a-f]{64}$')
    AND (validation_hash IS NULL OR validation_hash ~ '^[0-9a-f]{64}$')
  ),
  CONSTRAINT chk_tenant_migration_counts CHECK(
    jsonb_typeof(source_row_counts)='object'
    AND jsonb_typeof(target_row_counts)='object'
  )
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_tenant_migration_active
  ON tenant_migration_jobs(tenant_id)
  WHERE status IN (
    'planned','freezing','exporting','restoring','validating','cutover'
  );
CREATE INDEX IF NOT EXISTS idx_tenant_migration_status
  ON tenant_migration_jobs(status,updated_at,tenant_id);

