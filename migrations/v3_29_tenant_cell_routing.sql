CREATE OR REPLACE FUNCTION seed_tenant_placement()
RETURNS trigger LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO furniscope,public AS $$
DECLARE configured_cell text;
DECLARE selected_cell deployment_cells%ROWTYPE;
BEGIN
  configured_cell := nullif(current_setting('furniscope.cell_code',true),'');
  SELECT * INTO selected_cell
    FROM deployment_cells
   WHERE status='active'
     AND (cell_code=configured_cell OR (configured_cell IS NULL AND is_default))
   ORDER BY (cell_code=configured_cell) DESC,is_default DESC,cell_code
   LIMIT 1;
  IF selected_cell.cell_code IS NULL THEN
    RAISE EXCEPTION 'no active deployment cell is configured'
      USING ERRCODE='55000';
  END IF;
  INSERT INTO tenant_placements(
    tenant_id,cell_code,residency_region,service_tier,status
  ) VALUES(
    NEW.id,selected_cell.cell_code,selected_cell.region_code,'standard','active'
  ) ON CONFLICT(tenant_id) DO NOTHING;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_tenants_seed_placement ON tenants;
CREATE TRIGGER trg_tenants_seed_placement
AFTER INSERT ON tenants FOR EACH ROW EXECUTE FUNCTION seed_tenant_placement();

CREATE OR REPLACE FUNCTION enforce_tenant_write_fence()
RETURNS trigger LANGUAGE plpgsql
SET search_path TO furniscope,public AS $$
DECLARE target_tenant_id bigint;
DECLARE placement_status text;
DECLARE active_migration uuid;
DECLARE bypass_token text;
BEGIN
  IF TG_TABLE_NAME='tenants' THEN
    IF TG_OP='INSERT' THEN RETURN NEW; END IF;
    target_tenant_id := OLD.id;
  ELSIF TG_OP='DELETE' THEN
    target_tenant_id := OLD.tenant_id;
  ELSE
    target_tenant_id := NEW.tenant_id;
  END IF;
  IF target_tenant_id IS NULL THEN
    RETURN CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END;
  END IF;
  SELECT status,migration_uuid
    INTO placement_status,active_migration
    FROM tenant_placements
   WHERE tenant_id=target_tenant_id;
  IF placement_status IS NULL OR placement_status='active' THEN
    RETURN CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END;
  END IF;
  bypass_token := nullif(current_setting('furniscope.migration_bypass',true),'');
  IF active_migration IS NOT NULL
     AND bypass_token=active_migration::text
     AND (
       pg_has_role(session_user,'furniscope_migrator','MEMBER')
       OR EXISTS(SELECT FROM pg_roles WHERE rolname=session_user AND rolsuper)
     ) THEN
    RETURN CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END;
  END IF;
  RAISE EXCEPTION 'tenant % writes are fenced while placement status is %',
    target_tenant_id,placement_status
    USING ERRCODE='55000';
END $$;

DO $$
DECLARE table_name text;
BEGIN
  FOR table_name IN
    SELECT c.relname
      FROM pg_class c
      JOIN pg_namespace n ON n.oid=c.relnamespace
     WHERE n.nspname='furniscope' AND c.relkind IN ('r','p')
       AND NOT c.relispartition
       AND (
         c.relname='tenants'
         OR EXISTS(
           SELECT FROM pg_attribute a
            WHERE a.attrelid=c.oid AND a.attname='tenant_id'
              AND NOT a.attisdropped
         )
       )
       AND c.relname<>ALL(ARRAY[
         'tenant_placements','tenant_migration_jobs','audit_logs',
         'tenant_legal_holds','tenant_deletion_requests',
         'tenant_deletion_certificates'
       ])
  LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS trg_tenant_write_fence ON %I',table_name);
    EXECUTE format(
      'CREATE TRIGGER trg_tenant_write_fence
       BEFORE INSERT OR UPDATE OR DELETE ON %I
       FOR EACH ROW EXECUTE FUNCTION enforce_tenant_write_fence()',
      table_name
    );
  END LOOP;
END $$;

ALTER TABLE tenant_placements ENABLE ROW LEVEL SECURITY;
