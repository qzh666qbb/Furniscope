CREATE OR REPLACE FUNCTION furniscope.invalidate_enterprise_dependent_memories()
RETURNS trigger LANGUAGE plpgsql
SET search_path TO furniscope,public AS $$
BEGIN
  IF NEW.profile_version IS DISTINCT FROM OLD.profile_version THEN
    UPDATE customer_memories
       SET status='invalidated',invalidated_at=CURRENT_TIMESTAMP,
           invalidation_reason='enterprise_profile_version_changed',
           updated_at=CURRENT_TIMESTAMP
     WHERE tenant_id=NEW.tenant_id AND status='confirmed'
       AND COALESCE((profile_dependencies->>'invalidate_on_profile_change')::boolean,FALSE)
       AND profile_dependencies->>'enterprise_profile_version'=OLD.profile_version::text;
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_enterprise_memory_invalidation ON enterprise_profiles;
CREATE TRIGGER trg_enterprise_memory_invalidation
  AFTER UPDATE OF profile_version ON enterprise_profiles
  FOR EACH ROW EXECUTE FUNCTION furniscope.invalidate_enterprise_dependent_memories();

CREATE OR REPLACE FUNCTION furniscope.invalidate_product_dependent_memories()
RETURNS trigger LANGUAGE plpgsql
SET search_path TO furniscope,public AS $$
BEGIN
  IF NEW.current_profile_version_id IS DISTINCT FROM OLD.current_profile_version_id
     AND OLD.current_profile_version_id IS NOT NULL THEN
    UPDATE customer_memories
       SET status='invalidated',invalidated_at=CURRENT_TIMESTAMP,
           invalidation_reason='product_profile_version_changed',
           updated_at=CURRENT_TIMESTAMP
     WHERE tenant_id=NEW.tenant_id AND status='confirmed'
       AND COALESCE((profile_dependencies->>'invalidate_on_profile_change')::boolean,FALSE)
       AND profile_dependencies->>'product_id'=NEW.id::text
       AND profile_dependencies->>'product_profile_version_id'=OLD.current_profile_version_id::text;
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_product_memory_invalidation ON products;
CREATE TRIGGER trg_product_memory_invalidation
  AFTER UPDATE OF current_profile_version_id ON products
  FOR EACH ROW EXECUTE FUNCTION furniscope.invalidate_product_dependent_memories();

