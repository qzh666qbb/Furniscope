-- Preserve the oldest active turn and fail duplicate in-flight rows before
-- installing the serialization constraint on upgraded databases.
WITH pending AS (
  SELECT id,row_number() OVER(
    PARTITION BY tenant_id,workspace_id ORDER BY started_at,id
  ) AS position
  FROM analysis_workspace_turns
  WHERE status='pending'
)
UPDATE analysis_workspace_turns t
   SET status='failed',error_code='TURN_SUPERSEDED_BY_SERIALIZATION',
       completed_at=CURRENT_TIMESTAMP,updated_at=CURRENT_TIMESTAMP
  FROM pending p
 WHERE p.id=t.id AND p.position>1;
