-- Archive every entity that will be removed or whose workflow-specific columns will be discarded.
CREATE OR REPLACE FUNCTION pg_temp.archive_table(p_table TEXT, p_pk TEXT, p_tenant_expr TEXT) RETURNS void
LANGUAGE plpgsql AS $$
DECLARE sql_text TEXT;
BEGIN
  sql_text := format(
    'INSERT INTO furniscope_archive.retired_entity_rows(source_schema,source_table,source_pk,tenant_id,row_data) '
    || 'SELECT %L,%L,(%s)::text,(%s)::bigint,to_jsonb(t) FROM furniscope.%I t',
    'furniscope',p_table,p_pk,p_tenant_expr,p_table
  );
  EXECUTE sql_text;
END;
$$;

