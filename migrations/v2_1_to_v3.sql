-- FurniScope V2.1 -> V3.0 migration
-- PostgreSQL 16+
-- The migration is transactional. Any failure rolls back data moves, table drops and constraints.
-- Run only after taking a physical backup and testing on a database copy.

\set ON_ERROR_STOP on
BEGIN;
SET LOCAL lock_timeout = '10s';
SET LOCAL statement_timeout = '15min';
SET search_path TO furniscope, public;

-- Serialize schema migration.
SELECT pg_advisory_xact_lock(hashtext('furniscope:v2_1_to_v3'));

-- V2.1 attached this generic trigger to some tables without updated_at.
-- Remove legacy instances before rewrites; V3 recreates only valid instances.
DO $$
DECLARE r RECORD;
BEGIN
  FOR r IN
    SELECT n.nspname,c.relname,t.tgname
    FROM pg_trigger t
    JOIN pg_class c ON c.oid=t.tgrelid
    JOIN pg_namespace n ON n.oid=c.relnamespace
    JOIN pg_proc p ON p.oid=t.tgfoid
    WHERE n.nspname='furniscope' AND NOT t.tgisinternal AND p.proname='set_updated_at'
  LOOP
    EXECUTE format('DROP TRIGGER %I ON %I.%I',r.tgname,r.nspname,r.relname);
  END LOOP;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema='furniscope' AND table_name='roles') THEN
    RAISE EXCEPTION 'V2.1 baseline not detected: furniscope.roles is missing';
  END IF;
  IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema='furniscope' AND table_name='user_confirmations') THEN
    RAISE EXCEPTION 'V3 user_confirmations already exists; migration is not re-entrant';
  END IF;
END $$;

