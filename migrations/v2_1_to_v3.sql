-- Validate all merged row counts and JSON shapes BEFORE dropping source tables.
DO $$
DECLARE src BIGINT; dst BIGINT;
BEGIN
  SELECT count(*) INTO src FROM enterprise_constraints;
  SELECT COALESCE(sum(jsonb_array_length(constraints)),0) INTO dst FROM enterprise_profiles;
  IF src<>dst THEN RAISE EXCEPTION 'enterprise constraint migration mismatch: % <> %',src,dst; END IF;

  SELECT count(*) INTO src FROM dataset_field_mappings;
  SELECT COALESCE(sum(jsonb_array_length(field_mapping)),0) INTO dst FROM market_datasets;
  IF src<>dst THEN RAISE EXCEPTION 'field mapping migration mismatch: % <> %',src,dst; END IF;

  SELECT count(*) INTO src FROM listing_attributes;
  SELECT count(*) INTO dst FROM market_listings l CROSS JOIN LATERAL jsonb_object_keys(COALESCE(l.normalized_attributes,'{}'::jsonb)) k;
  IF dst<src THEN RAISE EXCEPTION 'listing attribute migration lost rows: % > %',src,dst; END IF;

  SELECT count(*) INTO src FROM competitor_set_confirmations;
  SELECT count(*) INTO dst FROM user_confirmations WHERE idempotency_key LIKE 'legacy-competitor-confirmation-%';
  IF src<>dst THEN RAISE EXCEPTION 'confirmation migration mismatch: % <> %',src,dst; END IF;

  IF EXISTS(SELECT 1 FROM users WHERE role_code NOT IN ('user','admin')) THEN RAISE EXCEPTION 'legacy role remains'; END IF;
  IF EXISTS(SELECT 1 FROM analysis_tasks WHERE external_stage IS NULL OR internal_stage IN ('competitor_review','expert_review')) THEN RAISE EXCEPTION 'task stage projection invalid'; END IF;
  IF EXISTS(SELECT 1 FROM analysis_reports WHERE jsonb_typeof(sections)<>'array' OR jsonb_array_length(sections)=0) THEN RAISE EXCEPTION 'report section merge invalid'; END IF;

  -- Fail inside the transaction if a legacy physical name survived. This prevents
  -- an apparently successful migration from exposing a schema that V3 code cannot query.
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema='furniscope'
      AND ((table_name='enterprise_profiles' AND column_name='business_models')
        OR (table_name='analysis_tasks' AND column_name='product_profile_version')
        OR (table_name IN ('competitor_matches','review_aspects','insight_clusters','market_metrics','price_bands','market_opportunities','evidence_links','analysis_reports') AND column_name='task_id'))
  ) THEN RAISE EXCEPTION 'legacy V2.1 physical column survived V3 migration'; END IF;
  IF (SELECT count(*) FROM information_schema.columns
      WHERE table_schema='furniscope'
        AND ((table_name='enterprise_profiles' AND column_name='business_model')
          OR (table_name IN ('competitor_matches','review_aspects','insight_clusters','market_metrics','price_bands','market_opportunities','evidence_links','analysis_reports') AND column_name='analysis_job_id'))) <> 9
  THEN RAISE EXCEPTION 'required V3 physical columns are incomplete'; END IF;
END $$;

