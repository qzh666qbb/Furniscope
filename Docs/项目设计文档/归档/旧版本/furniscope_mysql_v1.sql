-- FurniScope MySQL Database Schema V1.0
-- Target: MySQL 8.0+
-- Charset: utf8mb4

CREATE DATABASE IF NOT EXISTS furniscope
  DEFAULT CHARACTER SET utf8mb4
  DEFAULT COLLATE utf8mb4_0900_ai_ci;

USE furniscope;

SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

-- =========================================================
-- A. Business master data
-- =========================================================

CREATE TABLE IF NOT EXISTS tenants (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT 'Tenant primary key',
  tenant_code VARCHAR(32) NOT NULL COMMENT 'Globally unique tenant code',
  tenant_name VARCHAR(200) NOT NULL COMMENT 'Enterprise legal/display name',
  display_name VARCHAR(100) DEFAULT NULL COMMENT 'Enterprise short name',
  industry VARCHAR(64) NOT NULL DEFAULT 'furniture_manufacturing' COMMENT 'Industry code',
  default_timezone VARCHAR(64) NOT NULL DEFAULT 'Asia/Shanghai' COMMENT 'IANA timezone',
  default_currency CHAR(3) NOT NULL DEFAULT 'CNY' COMMENT 'ISO 4217 currency',
  status TINYINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '0 disabled, 1 active, 2 suspended',
  data_retention_days INT UNSIGNED NOT NULL DEFAULT 365 COMMENT 'Default data retention days',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  deleted_at DATETIME(3) DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_tenants_code (tenant_code),
  KEY idx_tenants_status (status)
) ENGINE=InnoDB COMMENT='Enterprise tenants';

CREATE TABLE IF NOT EXISTS users (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT 'User primary key',
  tenant_id BIGINT UNSIGNED NOT NULL COMMENT 'Tenant ID',
  email VARCHAR(254) NOT NULL COMMENT 'Login email, normalized lowercase',
  password_hash VARCHAR(255) NOT NULL COMMENT 'Password hash; never plaintext',
  user_name VARCHAR(100) NOT NULL COMMENT 'User display name',
  phone VARCHAR(32) DEFAULT NULL COMMENT 'Phone in E.164 format',
  department VARCHAR(100) DEFAULT NULL COMMENT 'Department',
  job_title VARCHAR(100) DEFAULT NULL COMMENT 'Job title',
  role_code VARCHAR(32) NOT NULL DEFAULT 'market_ops' COMMENT 'owner/product_rd/market_ops/sales/admin',
  locale VARCHAR(16) NOT NULL DEFAULT 'zh-CN' COMMENT 'BCP 47 locale',
  timezone VARCHAR(64) DEFAULT NULL COMMENT 'IANA timezone; null inherits tenant',
  status TINYINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '0 disabled, 1 active, 2 invited, 3 locked',
  last_login_at DATETIME(3) DEFAULT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  deleted_at DATETIME(3) DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_users_tenant_email (tenant_id, email),
  KEY idx_users_tenant_role_status (tenant_id, role_code, status),
  CONSTRAINT fk_users_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id)
) ENGINE=InnoDB COMMENT='System users';

CREATE TABLE IF NOT EXISTS enterprise_profiles (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  tenant_id BIGINT UNSIGNED NOT NULL,
  business_models JSON NOT NULL COMMENT 'B2B/B2C/OEM/ODM/brand array',
  primary_categories JSON NOT NULL COMMENT 'Primary category code array',
