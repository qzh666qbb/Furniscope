  PRIMARY KEY (id),
  UNIQUE KEY uk_enterprise_profiles_tenant (tenant_id),
  CONSTRAINT fk_enterprise_profiles_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id),
  CONSTRAINT fk_enterprise_profiles_confirmer FOREIGN KEY (confirmed_by) REFERENCES users (id)
