CREATE TABLE IF NOT EXISTS manufacturing_capabilities (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  tenant_id BIGINT UNSIGNED NOT NULL,
  capability_type VARCHAR(32) NOT NULL COMMENT 'category/material/process/customization/packaging/certification/delivery/equipment',
  capability_code VARCHAR(100) NOT NULL,
  capability_name VARCHAR(200) NOT NULL,
  availability TINYINT UNSIGNED NOT NULL DEFAULT 2 COMMENT '0 no, 1 yes, 2 unknown',
  min_value DECIMAL(18,4) DEFAULT NULL,
  max_value DECIMAL(18,4) DEFAULT NULL,
  unit VARCHAR(32) DEFAULT NULL,
  valid_from DATE DEFAULT NULL,
  valid_until DATE DEFAULT NULL,
  source_type VARCHAR(32) NOT NULL DEFAULT 'confirmed_user',
  confidence DECIMAL(5,4) NOT NULL DEFAULT 1.0000 COMMENT '0-1',
  evidence_url VARCHAR(1000) DEFAULT NULL COMMENT 'Authorized evidence object URL/key',
  notes VARCHAR(1000) DEFAULT NULL,
  created_by BIGINT UNSIGNED DEFAULT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  deleted_at DATETIME(3) DEFAULT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_capability_tenant_type_code (tenant_id, capability_type, capability_code),
  KEY idx_capability_tenant_available (tenant_id, availability, capability_type),
  KEY idx_capability_valid_until (tenant_id, valid_until),
  CONSTRAINT fk_capability_tenant FOREIGN KEY (tenant_id) REFERENCES tenants (id),
  CONSTRAINT fk_capability_creator FOREIGN KEY (created_by) REFERENCES users (id),
  CONSTRAINT chk_capability_range CHECK (max_value IS NULL OR min_value IS NULL OR max_value >= min_value),
  CONSTRAINT chk_capability_confidence CHECK (confidence BETWEEN 0 AND 1)
